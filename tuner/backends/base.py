from datetime import datetime
from typing import Protocol

from tuner.core.types import Capabilities, CrashEvent, Limits, Telemetry, Timing


class Backend(Protocol):
    def read_capabilities(self) -> Capabilities: ...
    def read_limits(self) -> Limits: ...
    def read_telemetry(self) -> Telemetry: ...
    def set_voltage(self, reduction_mv: int) -> None: ...
    def set_vram(self, mhz: int, timing: Timing) -> None: ...
    def reset(self) -> None: ...
    def crash_events_since(self, t: datetime) -> list[CrashEvent]: ...
